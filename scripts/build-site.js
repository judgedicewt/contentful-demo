/**
 * Writes site/config.js from the environment so the static front end knows
 * which space to read. Used locally and by the GitHub Pages workflow.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadConfig } from '../src/config.js';

const config = loadConfig();
const needed = ['CONTENTFUL_SPACE_ID', 'CONTENTFUL_ENVIRONMENT', 'CONTENTFUL_DELIVERY_TOKEN'];
const missing = needed.filter((name) => !process.env[name]);
if (missing.length > 0) {
  console.error(`Missing required variables: ${missing.join(', ')}`);
  process.exit(1);
}

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'site', 'config.js');
const contents = `// Generated by scripts/build-site.js. Do not edit; do not commit.
window.CONTENTFUL_CONFIG = ${JSON.stringify(
  { spaceId: config.spaceId, environment: config.environmentId, deliveryToken: config.deliveryToken },
  null,
  2,
)};
`;
writeFileSync(target, contents);
console.log(`Wrote ${target} for space ${config.spaceId} / ${config.environmentId}`);
