const PLACEHOLDER = /\{(\w+)\}/g;

/**
 * Looks up `key` for `lang`, falling back to English and then to the key
 * itself, and fills each `{name}` from `vars`. A missing var renders as ''.
 *
 * Returns a string when every used var is a string, number, or missing. When
 * any used var is an object (a `SafeHtml` from `html`), returns an array of
 * alternating literal strings and var values, which the `html` tag
 * interpolates with the literals escaped and the objects trusted.
 */
export function t(key, lang = DEFAULT_LANG, vars = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  const pieces = template.split(PLACEHOLDER);
  const values = [];
  let markup = false;
  for (let i = 1; i < pieces.length; i += 2) {
    const value = vars?.[pieces[i]] ?? '';
    if (typeof value === 'object') markup = true;
    values.push(value);
  }
  if (!markup) {
    return pieces.map((piece, i) => (i % 2 ? String(values[(i - 1) / 2]) : piece)).join('');
  }
  return pieces.map((piece, i) => (i % 2 ? values[(i - 1) / 2] : piece));
}
